export function shouldReconnect(event: CloseEvent): boolean {
  switch (event.code) {
    // 1002 - ошибка протокола
    case 1002:
    // 1003 - сервер получил неподдерживаемый тип данных
    case 1003:
    // 1007 - некорректные данные в кадре
    case 1007:
    // 1008 - нарушение политики
    case 1008:
    // 1009 - слишком большое сообщение
    case 1009:
    // 1010 - клиент требует расширение, сервер не поддерживает
    case 1010:
    // 1015 - ошибка TLS-рукопожатия
    case 1015:
      return false;

    // 1001 - сервер уходит (рестарт, деплой, балансировщик)
    case 1001:
    // 1005 - код не был передан, браузер подставил сам
    case 1005:
    // 1006 - соединение оборвалось без close-фрейма (сеть, краш)
    case 1006:
    // 1011 - внутренняя ошибка сервера
    case 1011:
    // 1012 - сервис перезапускается
    case 1012:
    // 1013 - сервер перегружен, попробуйте позже
    case 1013:
    // 1014 - плохой шлюз
    case 1014:
      return true;

    // 1000 (Normal) и всё остальное - по признаку чистого закрытия:
    // нечистое (обрыв) -> переподключаемся, чистое -> нет
    default:
      return !event.wasClean;
  }
}